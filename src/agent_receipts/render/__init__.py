"""Render receipts as Markdown (for PR comments) or JSON (for CI artifacts)."""

from __future__ import annotations

import hashlib
import json
import re

from jinja2 import Environment

from agent_receipts.models import SEVERITY_ORDER, Receipt

GLYPH = {"VERIFIED": "✔", "STALE": "◷", "FAILED": "✖", "UNVERIFIED": "?"}
ALERT = {"critical": "CAUTION", "high": "WARNING", "medium": "NOTE", "low": "NOTE", "info": "NOTE"}

TEMPLATE = """<!-- agent-receipts -->
### 🧾 Agent receipt — {{ glyph }} {{ r.verdict.status }}
{{ r.verdict.reason|text }}

| Files | Commands | Findings | Tokens |
|---|---|---|---|
| {{ r.files_changed|length }} | {{ r.usage.commands_run }} | {{ findings_summary }} | {{ tokens }} |
{% for f in top %}

> [!{{ alert[f.severity] }}]
> **{{ f.rule_id|text }} · {{ f.severity }}** — {{ f.title|text }}: {{ f.evidence|code }} (step {{ f.event_idx }})
{% endfor %}
{% if more %}

<details><summary>+{{ more_total }} more findings</summary>

{% for f in more %}
- **{{ f.rule_id|text }} · {{ f.severity }}** — {{ f.title|text }}: {{ f.evidence|code }} (step {{ f.event_idx }})
{% endfor %}
{% if more_total > more|length %}
- … and {{ more_total - more|length }} more (see the JSON receipt)
{% endif %}

</details>
{% endif %}

<details><summary>Files changed ({{ r.files_changed|length }}) · Assumptions ({{ r.assumptions|length }}) · Tools & MCP ({{ r.usage.tool_counts|length }}) · Sessions ({{ r.sessions|length }})</summary>

**Files changed**

{% for p in files %}
- {{ p|code }}
{% else %}
- none
{% endfor %}
{% if r.files_changed|length > files|length %}
- … and {{ r.files_changed|length - files|length }} more
{% endif %}

**Checks run:** {% if r.verdict.checks %}{% for c in r.verdict.checks[:20] %}{{ c|code }}{% if not loop.last %} · {% endif %}{% endfor %}{% else %}none{% endif %}


**Assumptions the agent stated**

{% for a in r.assumptions[:10] %}
- {{ a|text }}
{% else %}
- none found
{% endfor %}

**Tools:** {% for k, v in tools %}{{ k|text }} ×{{ v }}{% if not loop.last %} · {% endif %}{% endfor %}{% if r.usage.mcp_servers %} · **MCP servers:** {{ r.usage.mcp_servers[:20]|map('text')|join(', ') }}{% endif %}


**Sessions**

{% for s in r.sessions[:20] %}
- {{ s.harness }}{% if s.models %} ({{ s.models|map('text')|join(', ') }}){% endif %} · {{ s.events }} events{% if s.unknown_records %} · {{ s.unknown_records }} unrecognised records{% endif %}

{% endfor %}
</details>

<sub>generated by {{ r.generator|text }} · receipt sha256:{{ digest }}{% if head %} · head {{ head }}{% endif %}</sub>
"""

MARKER = "<!-- agent-receipts -->"
MAX_FILES = 100
MAX_MORE_FINDINGS = 50

_URL = re.compile(r"(?i)\b(?:https?://|ftp://|www\.)\S+")
_SPAN = re.compile(r"`([^`\n]*)`")
_MD_PUNCT = re.compile(r"([\\`*_\[\]|~#!])")
_MENTION = re.compile(r"@(?=[A-Za-z0-9_-])")
_HEX = re.compile(r"[0-9a-fA-F]{7,40}")


def _plain(s: str) -> str:
    """Escape free text so it renders literally: no HTML, mentions, links or formatting."""
    out = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    out = _MD_PUNCT.sub(r"\\\1", out)
    return _MENTION.sub("@\u200b", out)


def md_code(value: object) -> str:
    """Render untrusted text as one inline code span (mentions, HTML and links are inert there)."""
    s = " ".join(str(value or "").split()).replace("`", "'")
    return f"`{s}`" if s else "`(empty)`"


def md_text(value: object) -> str:
    """Render untrusted text as safe single-line Markdown.

    Newlines are collapsed (no injected headings, tables or ``<details>``), raw HTML is
    escaped, ``@mentions`` get a zero-width space so nobody is pinged, URLs become inert
    code spans, Markdown punctuation is escaped, and paired backticks stay code spans.
    """
    s = " ".join(str(value or "").split())
    parts: list[str] = []
    pos = 0
    for m in _SPAN.finditer(s):
        parts.append(_text_with_urls(s[pos : m.start()]))
        parts.append(md_code(m.group(1)))
        pos = m.end()
    parts.append(_text_with_urls(s[pos:]))
    return "".join(parts)


def _text_with_urls(s: str) -> str:
    parts: list[str] = []
    pos = 0
    for m in _URL.finditer(s):
        parts.append(_plain(s[pos : m.start()]))
        parts.append(md_code(m.group(0)))
        pos = m.end()
    parts.append(_plain(s[pos:]))
    return "".join(parts)


_env = Environment(autoescape=False, trim_blocks=True, lstrip_blocks=True)  # noqa: S701 - Markdown output
_env.filters["text"] = md_text
_env.filters["code"] = md_code
_tpl = _env.from_string(TEMPLATE)


def _tokens(n: int) -> str:
    if n >= 1_000_000:
        return f"{n / 1_000_000:.1f}M"
    if n >= 1000:
        return f"{round(n / 1000)}k"
    return str(n)


def to_json(r: Receipt) -> str:
    return r.model_dump_json(indent=2)


def digest(r: Receipt) -> str:
    return hashlib.sha256(
        json.dumps(r.model_dump(mode="json"), sort_keys=True).encode()
    ).hexdigest()[:12]


def to_markdown(r: Receipt) -> str:
    counts: dict[str, int] = {}
    for f in r.findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1
    summary = (
        " · ".join(f"{counts[s]} {s}" for s in sorted(counts, key=SEVERITY_ORDER.__getitem__))
        or "none"
    )
    serious = [f for f in r.findings if SEVERITY_ORDER[f.severity] <= SEVERITY_ORDER["medium"]]
    top, rest = serious[:5], serious[5:] + [f for f in r.findings if f not in serious]
    head = r.head_sha[:7] if r.head_sha and _HEX.fullmatch(r.head_sha) else None
    return _tpl.render(
        r=r,
        glyph=GLYPH[r.verdict.status],
        findings_summary=summary,
        tokens=_tokens(r.usage.total_tokens),
        top=top,
        more=rest[:MAX_MORE_FINDINGS],
        more_total=len(rest),
        files=r.files_changed[:MAX_FILES],
        tools=list(r.usage.tool_counts.items())[:30],
        head=head,
        alert=ALERT,
        digest=digest(r),
    )
